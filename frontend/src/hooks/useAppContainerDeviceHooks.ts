import { useEffect } from "react";
import { useAppContainerDeviceActions } from "./useAppContainerDeviceActions";
import { useDeviceEditorActions } from "./useDeviceEditorActions";
import { useScheduleActions } from "./useScheduleActions";
import { useDevicesPage } from "./useDevicesPage";
import type { UseDeviceActionsOptions } from "./useDeviceActions";
import type { UseAppContainerDeviceHooksOptions } from "./types/useAppContainerDeviceHooksOptions";

export function useAppContainerDeviceHooks(options: UseAppContainerDeviceHooksOptions) {
  const {
    baseUrl,
    devices,
    groups,
    discoveredDevices,
    selectedDiscoveredDevices,
    refreshAll,
    loadGroups,
    recordDeviceEvent,
    showToast,
    showMessage,
    showConfirm,
    setStatusMessage,
    setDevices,
    setDiscoveryLoading,
    setDiscoveredDevices,
    setSelectedDiscoveredDevices,
    setDiscoveryModalOpen,
    setShowDiscoveryModal,
    groupName,
    setGroupName,
    selectedAssignGroupId,
    setSelectedAssignGroupId,
    setShowAssignGroupModal,
    forcedOffIdsRef,
    editingId,
    deviceName,
    deviceIp,
    deviceMac,
    deviceBrand,
    modalGroupId,
    selectedDeviceId,
    pendingDelete,
    showModal,
    showDiscoveryModal,
    messageModal,
    setEditingId,
    setDeviceName,
    setDeviceIp,
    setDeviceMac,
    setDeviceBrand,
    setModalGroupId,
    setShowModal,
    setSelectedDeviceId,
    setPendingDelete,
    setShowDeleteConfirm,
    setMessageModal,
    setDetailTab,
    scheduleAction,
    scheduleSequence,
    scheduleDescription,
    scheduleEnabled,
    scheduleTarget,
    setDeviceSchedules,
    setScheduleCron,
    setScheduleAction,
    setScheduleTarget,
    setScheduleDescription,
    setScheduleEnabled,
    setScheduleSequence,
    setScheduleUseTime,
    setScheduleTime,
    setEditingScheduleId,
    navigate,
    loadAuditLogs,
    auditPageSize,
    deviceHistory,
    search,
    groupFilter,
    statusFilter,
    powerFilter,
    activityFilter,
    registrationFrom,
    registrationTo,
    discoveryLoading,
    setAuditDeviceFilter,
    setAuditGroupFilter,
    setAuditPage,
    closeMessageModal,
  } = options;

  const deviceActionOptions = {
    baseUrl,
    devices,
    groups,
    discoveredDevices,
    selectedDiscoveredDevices,
    refreshAll,
    loadGroups,
    recordDeviceEvent,
    showToast,
    showMessage,
    showConfirm,
    setStatusMessage,
    setDevices,
    setDiscoveryLoading,
    setDiscoveredDevices,
    setSelectedDiscoveredDevices,
    setDiscoveryModalOpen,
    groupName,
    setGroupName,
    selectedAssignGroupId,
    setSelectedAssignGroupId,
    setShowAssignGroupModal,
    forcedOffIdsRef,
  } as UseDeviceActionsOptions & { setDiscoveryModalOpen: (open: boolean) => void };

  const {
    handlePowerOnAll,
    handlePowerOffAll,
    handlePowerOffDevice,
    handlePowerOnDevice,
    handleRestartDevice,
    handleSendDeviceAction,
    handleStartDiscovery,
    handleAddDiscoveredDevices,
    closeDiscoveryModal,
    handleCreateGroup,
    handleRestartGroup,
    handlePowerOnGroup,
    handlePowerOffGroup,
    openAssignGroupModal,
    assignGroupToSelected,
    handleDeleteSelected,
    handleRestartSelected,
    toggleDevice,
  } = useAppContainerDeviceActions(deviceActionOptions);

  const {
    clearModalFields,
    handleOpenModal,
    handleSave,
    confirmDelete,
    cancelDelete,
    handleViewDevice,
  } = useDeviceEditorActions({
    baseUrl,
    devices,
    groups,
    editingId,
    deviceName,
    deviceIp,
    deviceMac,
    deviceBrand,
    modalGroupId,
    selectedDeviceId,
    pendingDelete,
    showModal,
    showDiscoveryModal,
    messageModal,
    setDevices,
    setEditingId,
    setDeviceName,
    setDeviceIp,
    setDeviceMac,
    setDeviceBrand,
    setModalGroupId,
    setShowModal,
    setSelectedDeviceId,
    setPendingDelete,
    setShowDeleteConfirm,
    setShowDiscoveryModal,
    setMessageModal,
    setStatusMessage,
    setDetailTab,
    showMessage,
  });

  const {
    loadDeviceSchedules,
    clearScheduleForm,
    handleEditSchedule,
    handleDeleteSchedule,
    handleToggleSchedule,
    fetchScheduleLogs,
    handleTriggerSchedule,
    handleSaveScheduleBuilder,
  } = useScheduleActions({
    baseUrl,
    selectedDevice: devices.find((device) => device.id === selectedDeviceId) || null,
    selectedDeviceId,
    scheduleAction,
    scheduleSequence,
    scheduleDescription,
    scheduleEnabled,
    scheduleTarget,
    setDeviceSchedules,
    setDetailTab,
    setScheduleCron,
    setScheduleAction,
    setScheduleTarget,
    setScheduleDescription,
    setScheduleEnabled,
    setScheduleSequence,
    setScheduleUseTime,
    setScheduleTime,
    setEditingScheduleId,
    showMessage,
  });

  useEffect(() => {
    if (selectedDeviceId === null) {
      return;
    }

    void loadDeviceSchedules(selectedDeviceId);
  }, [selectedDeviceId, loadDeviceSchedules]);

  const {
    selectedDevice,
    filteredDevices,
    selectedDeviceHistory,
    recentDeviceEvents,
    groupStatusSummary,
    handleOpenDiscovery,
    handleOpenAuditForDevice,
    handleOpenAuditForGroup,
    handleClearSelection,
    handleMessageConfirm,
  } = useDevicesPage({
    devices,
    deviceHistory,
    groups,
    selectedDeviceId,
    search,
    groupFilter,
    statusFilter,
    powerFilter,
    activityFilter,
    registrationFrom,
    registrationTo,
    showDiscoveryModal,
    discoveryLoading,
    discoveredDevices,
    messageModal,
    auditPageSize,
    navigate,
    loadAuditLogs,
    setAuditDeviceFilter,
    setAuditGroupFilter,
    setAuditPage,
    setShowModal,
    setShowDiscoveryModal,
    setSelectedDeviceId,
    closeMessageModal,
    handleStartDiscovery,
    showMessage,
  });

  return {
    handlePowerOnAll,
    handlePowerOffAll,
    handlePowerOffDevice,
    handlePowerOnDevice,
    handleRestartDevice,
    handleSendDeviceAction,
    handleStartDiscovery,
    handleAddDiscoveredDevices,
    closeDiscoveryModal,
    handleCreateGroup,
    handleRestartGroup,
    handlePowerOnGroup,
    handlePowerOffGroup,
    openAssignGroupModal,
    assignGroupToSelected,
    handleDeleteSelected,
    handleRestartSelected,
    toggleDevice,
    clearModalFields,
    handleOpenModal,
    handleSave,
    confirmDelete,
    cancelDelete,
    handleViewDevice,
    loadDeviceSchedules,
    clearScheduleForm,
    handleEditSchedule,
    handleDeleteSchedule,
    handleToggleSchedule,
    fetchScheduleLogs,
    handleTriggerSchedule,
    handleSaveScheduleBuilder,
    selectedDevice,
    filteredDevices,
    selectedDeviceHistory,
    recentDeviceEvents,
    groupStatusSummary,
    handleOpenDiscovery,
    handleOpenAuditForDevice,
    handleOpenAuditForGroup,
    handleClearSelection,
    handleMessageConfirm,
  };
}
